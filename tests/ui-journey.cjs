// End-to-end journey in the real desktop app: create → import → arrange → edit → style → export → reopen,
// plus a pixel comparison between the live preview and the exported file.
const { _electron: electron } = require('playwright');
const path = require('node:path'), fs = require('node:fs/promises'), os = require('node:os');
const assert = require('node:assert/strict');
const { run, ffmpeg, ffprobe } = require('../desktop/tools.cjs');
const shots = path.resolve('test-output');
const step = n => console.log('· ' + n);
(async () => {
  await fs.mkdir(shots, { recursive: true });
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'framecut-journey-')); let app, page; const errors = [];
  try {
    const clip = path.join(temp, 'Sunset drive.mp4'), clip2 = path.join(temp, 'City lights.mp4'), song = path.join(temp, 'Song.wav');
    await run(ffmpeg, ['-y', '-f', 'lavfi', '-i', 'testsrc2=s=1280x720:r=30', '-f', 'lavfi', '-i', 'sine=frequency=330:sample_rate=48000', '-t', '6', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', clip]);
    await run(ffmpeg, ['-y', '-f', 'lavfi', '-i', 'mandelbrot=s=1280x720:r=30', '-t', '5', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', clip2]);
    await run(ffmpeg, ['-y', '-f', 'lavfi', '-i', 'sine=frequency=220:sample_rate=48000', '-t', '10', song]);
    app = await electron.launch({ args: [path.resolve('.')], env: { ...process.env, FRAMECUT_TEST: '1', FRAMECUT_TEST_DIR: temp } });
    page = await app.firstWindow();
    page.on('pageerror', e => errors.push('pageerror: ' + e.message));
    page.on('requestfailed', r => r.failure()?.errorText !== 'net::ERR_ABORTED' && errors.push('requestfailed: ' + r.method() + ' ' + new URL(r.url()).pathname + ' ' + r.failure()?.errorText));
    page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
    await page.setViewportSize({ width: 1600, height: 960 });
    await page.getByText('New project').first().click();
    await page.locator('.editor').waitFor();
    step('import');
    await page.evaluate(async files => { const { state, api } = window.__fc; const r = await api('/api/media/import', { paths: files }); state.commit('Import', p => { for (const a of r.assets) p.mediaIds.push(a.id); }); await state.refreshMedia(); }, [clip, clip2, song]);
    await page.locator('.media-card').nth(1).waitFor();
    await page.waitForFunction(() => [...window.__fc.state.media.value.values()].every(a => a.kind !== 'video' || (a.strip && a.thumb)), null, { timeout: 30000 });
    step('add clips by double-click');
    await page.locator('.media-card', { hasText: 'Sunset drive' }).dblclick();
    await page.locator('.media-card', { hasText: 'City lights' }).dblclick();
    await page.locator('.clip').nth(1).waitFor();
    assert.equal(await page.locator('.track-row.main .clip').count(), 2);
    step('add music via audio tab');
    await page.locator('.rail-btn', { hasText: 'Audio' }).click();
    await page.evaluate(() => window.__fc.state.player.current.seek(0));
    await page.locator('.audio-row', { hasText: 'Song' }).locator('button[data-tip="Add at playhead"]').click();
    assert.equal(await page.locator('.track-row.k-audio .clip').count(), 1);
    await page.screenshot({ path: path.join(shots, '03-timeline.png') });
    step('split + undo + redo with shortcuts');
    await page.evaluate(() => { const { state } = window.__fc; state.selection.value = []; state.player.current.seek(2); document.activeElement?.blur(); });
    await page.keyboard.press('Control+b');
    assert.equal(await page.locator('.track-row.main .clip').count(), 3, 'split main clip');
    await page.keyboard.press('Control+z'); assert.equal(await page.locator('.track-row.main .clip').count(), 2, 'undo split');
    await page.keyboard.press('Control+y'); assert.equal(await page.locator('.track-row.main .clip').count(), 3, 'redo split');
    step('add text');
    await page.evaluate(() => window.__fc.state.player.current.seek(0.5));
    await page.keyboard.press('t');
    await page.locator('.insp-text textarea').waitFor();
    await page.locator('.insp-text textarea').fill('Hello FrameCut');
    await page.locator('.insp-text textarea').blur();
    step('transition between main clips');
    await page.locator('.rail-btn', { hasText: 'Transitions' }).click();
    await page.evaluate(() => { window.__fc.state.selection.value = []; window.__fc.state.player.current.seek(6); });
    await page.locator('.tr-tile', { hasText: 'Dissolve' }).click();
    const tr = await page.evaluate(() => window.__fc.state.project.value.clips.filter(c => c.transition).length); assert.ok(tr >= 1, 'transition applied');
    step('filter on first clip via selection');
    await page.locator('.track-row.main .clip').first().click({ position: { x: 20, y: 30 } });
    await page.locator('.rail-btn', { hasText: 'Filters' }).click();
    await page.locator('.fx-tile', { hasText: 'Teal & Orange' }).click();
    await page.locator('.insp-tabs button', { hasText: 'Color' }).click();
    await page.screenshot({ path: path.join(shots, '04-filter-inspector.png') });
    step('keyframes: add X key, drag the clip later in time (included in the preview/export comparison)');
    await page.locator('.insp-tabs button', { hasText: 'Basic' }).click();
    await page.evaluate(() => window.__fc.state.player.current.seek(0.2)); await page.waitForTimeout(200);
    await page.locator('.keyed').nth(1).locator('.kf-btn').click();
    await page.evaluate(() => window.__fc.state.player.current.seek(1.6)); await page.waitForTimeout(300);
    const gz = await page.locator('.gizmo').boundingBox();
    await page.mouse.move(gz.x + gz.width / 2, gz.y + gz.height / 2); await page.mouse.down();
    await page.mouse.move(gz.x + gz.width / 2 + 120, gz.y + gz.height / 2 + 1, { steps: 6 }); await page.mouse.up();
    const kf = await page.evaluate(() => { const s = window.__fc.state; const c = s.project.value.clips.find(c => c.id === s.selection.value[0]); return { keys: c.keyframes?.x, staticX: c.transform.x }; });
    console.log('  keys ' + JSON.stringify(kf));
    assert.equal(kf.keys?.length, 2, 'two X keyframes'); assert.ok(kf.keys[1].v > kf.keys[0].v + 0.05, 'second key moved right'); assert.equal(kf.staticX || 0, 0, 'static X untouched');
    assert.ok(await page.locator('.track-row.main .clip-key').count() >= 2, 'diamonds on the timeline clip');
    await page.screenshot({ path: path.join(shots, '05-keyframes.png') });
    step('volume envelope: double-click adds a point, drag lowers it');
    await page.locator('.track-row.k-audio .clip').first().click({ position: { x: 30, y: 8 } });
    const env = await page.locator('.track-row.k-audio .clip .envelope.on').boundingBox();
    await page.mouse.dblclick(env.x + 200, env.y + env.height / 2);
    await page.waitForFunction(() => window.__fc.state.project.value.clips.find(c => c.kind === 'audio')?.volumeKeys?.length === 1, null, { timeout: 5000, polling: 100 });
    await page.locator('.env-pt').first().waitFor(); await page.waitForTimeout(150);
    const pt = await page.locator('.env-pt').first().boundingBox();
    await page.mouse.move(pt.x + 4, pt.y + 4); await page.mouse.down(); await page.mouse.move(pt.x + 4, pt.y + 4 + env.height * 0.3, { steps: 5 }); await page.mouse.up();
    await page.waitForFunction(() => window.__fc.state.project.value.clips.find(c => c.kind === 'audio').volumeKeys?.[0]?.v < 0.7, null, { timeout: 5000, polling: 100 }).catch(() => {});
    const vk = await page.evaluate(() => window.__fc.state.project.value.clips.find(c => c.kind === 'audio').volumeKeys);
    console.log('  volume keys ' + JSON.stringify(vk));
    assert.equal(vk.length, 1); assert.ok(vk[0].v < 0.7 && vk[0].v > 0.2, 'point dragged down');
    await page.keyboard.press('Control+z'); await page.keyboard.press('Control+z');
    assert.ok(!(await page.evaluate(() => window.__fc.state.project.value.clips.find(c => c.kind === 'audio').volumeKeys)), 'undo removes the envelope');
    step('remove background (deterministic test matte) on the first clip');
    await page.evaluate(() => { window.__fc.matteEngine = 'synthetic'; window.__fc.state.player.current.seek(1.0); });
    await page.locator('.track-row.main .clip').first().click({ position: { x: 20, y: 30 } });
    await page.locator('.insp-tabs button', { hasText: 'Basic' }).click();
    await page.locator('.insp-section header', { hasText: 'Remove background' }).click().catch(() => {});
    await page.locator('button', { hasText: 'Remove background' }).last().click();
    await page.waitForFunction(() => window.__fc.state.project.value.clips.some(c => c.cutout), null, { timeout: 120000, polling: 200 });
    const cut = await page.evaluate(() => { const s = window.__fc.state; const c = s.project.value.clips.find(c => c.cutout); return { alpha: s.media.value.get(c.mediaId)?.alpha, inPt: c.in, orig: c.cutout }; });
    console.log('  cutout ' + JSON.stringify(cut));
    assert.ok(cut.alpha, 'cutout media has transparency');
    await page.locator('.matte-run').waitFor({ state: 'detached' }).catch(() => {});
    step('preview frame vs export');
    await page.evaluate(() => { const s = window.__fc.state; s.selection.value = []; s.player.current.seek(1.0); });
    await page.waitForTimeout(1200);
    const previewPng = await page.evaluate(() => window.__fc.state.player.current.canvas.toDataURL('image/png'));
    await fs.writeFile(path.join(shots, 'preview-1s.png'), Buffer.from(previewPng.split(',')[1], 'base64'));
    await page.screenshot({ path: path.join(shots, '05-editor-styled.png') });
    step('export through the dialog');
    const out = path.join(temp, 'out', 'Journey.mp4');
    await page.keyboard.press('Control+e');
    await page.waitForFunction(() => document.querySelector('.modal input[aria-label="Output file"]')?.value);
    await page.locator('.modal input[aria-label="Output file"]').fill(out);
    await page.locator('.modal .preset', { hasText: 'YouTube' }).first().click();
    await page.locator('.modal-foot .btn.primary').click();
    await page.getByText('Your video is ready').waitFor({ timeout: 120000 });
    await page.screenshot({ path: path.join(shots, '06-export-done.png') });
    const info = JSON.parse((await run(ffprobe, ['-v', 'quiet', '-show_streams', '-show_format', '-of', 'json', out])).out);
    const v = info.streams.find(s => s.codec_type === 'video'); assert.equal(v.height, 1080); assert.ok(info.streams.some(s => s.codec_type === 'audio'));
    const dur = await page.evaluate(() => window.__fc.state.duration.value); assert.ok(Math.abs(+info.format.duration - dur) < 0.15, `duration ${info.format.duration} vs ${dur}`);
    const W = 96, H = 54;
    const raw = async args => (await run(ffmpeg, args, { encoding: 'buffer' })).out;
    const exp = await raw(['-v', 'error', '-ss', '1.0', '-i', out, '-frames:v', '1', '-vf', `scale=${W}:${H}`, '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-']);
    const prev = await raw(['-v', 'error', '-i', path.join(shots, 'preview-1s.png'), '-vf', `scale=${W}:${H}`, '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-']);
    let diff = 0; for (let i = 0; i < exp.length; i++) diff += Math.abs(exp[i] - prev[i]); diff /= exp.length;
    console.log('  preview vs export mean abs diff (0-255):', diff.toFixed(2));
    await fs.writeFile(path.join(shots, 'export-1s.raw'), exp);
    await run(ffmpeg, ['-y', '-v', 'error', '-ss', '1.0', '-i', out, '-frames:v', '1', path.join(shots, 'export-1s.png')]);
    await page.locator('.modal-head .icon-btn').click();
    step('reopen project and verify persistence');
    const snap = () => page.evaluate(() => JSON.stringify(window.__fc.state.project.value.clips.map(c => [c.kind, c.start.toFixed(3), c.duration.toFixed(3), c.text || '', c.filter?.id || '', c.transition?.id || '']).sort()));
    const before = await snap();
    await page.locator('button[data-tip="Back to projects"]').click();
    await page.locator('.project-card').first().waitFor();
    await page.waitForTimeout(400);
    await page.screenshot({ path: path.join(shots, '07-home-recent.png') });
    await page.locator('.project-card').first().click();
    await page.locator('.editor').waitFor(); await page.waitForTimeout(500);
    assert.equal(await snap(), before, 'project reopened identically');
    const texts = await page.evaluate(() => window.__fc.state.project.value.clips.filter(c => c.kind === 'text').map(c => c.text)); assert.deepEqual(texts, ['Hello FrameCut'], 'typed text persisted');
    const order = await page.evaluate(() => window.__fc.state.project.value.clips.filter(c => c.trackId === 'main').sort((a, b) => a.start - b.start).map(c => c.name)); assert.equal(order[0], 'Sunset drive', 'clips added in order');
    assert.ok(diff < 8, 'preview matches export (diff ' + diff.toFixed(2) + ')');
    console.log('ERRORS', JSON.stringify(errors));
    assert.deepEqual(errors.filter(e => !/Autofill|DevTools/.test(e)), []);
    console.log('PASS: journey');
  } catch (e) { console.error('FAIL', e.message); await page?.screenshot({ path: path.join(shots, 'fail.png') }).catch(() => {}); console.log('ERRORS', JSON.stringify(errors)); process.exitCode = 1; }
  finally { await app?.close(); await fs.rm(temp, { recursive: true, force: true }).catch(() => {}); }
})();
