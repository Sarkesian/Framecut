// Audio studio in the real app with Chromium's fake microphone (a 440 Hz beep):
// record over the video → verify 24-bit WAV on disk → retake keeps both takes → Clean Voice →
// auto balance → ducking keys → waveform delete → export contains the mixed audio → reopen.
const { _electron: electron } = require('playwright');
const path = require('node:path'), fs = require('node:fs/promises'), os = require('node:os');
const assert = require('node:assert/strict');
const { run, ffmpeg, ffprobe } = require('../desktop/tools.cjs');
const shots = path.resolve('test-output');
const step = n => console.log('· ' + n);
(async () => {
  await fs.mkdir(shots, { recursive: true });
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'framecut-studio-')); let app, page; const errors = [];
  try {
    const clip = path.join(temp, 'Clip.mp4'), music = path.join(temp, 'Music.wav');
    await run(ffmpeg, ['-y', '-f', 'lavfi', '-i', 'testsrc2=s=1280x720:r=30', '-t', '8', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', clip]);
    await run(ffmpeg, ['-y', '-f', 'lavfi', '-i', 'sine=frequency=220:sample_rate=48000', '-t', '8', '-af', 'volume=0.5', music]);
    app = await electron.launch({ args: [path.resolve('.')], env: { ...process.env, FRAMECUT_TEST: '1', FRAMECUT_TEST_DIR: temp, FRAMECUT_FAKE_MEDIA: '1' } });
    page = await app.firstWindow();
    page.on('pageerror', e => errors.push('pageerror: ' + e.message));
    page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
    await page.setViewportSize({ width: 1600, height: 960 });
    await page.getByText('New project').first().click(); await page.locator('.editor').waitFor();
    await page.evaluate(async files => { const { state, api, edit } = window.__fc; const r = await api('/api/media/import', { paths: files }); await state.refreshMedia(); edit.addAssets([r.assets[0]], { at: 0 }); edit.addAssets([r.assets[1]], { at: 0 }); }, [clip, music]);
    await page.locator('.track-row.k-audio .clip').first().waitFor();
    step('open studio');
    await page.locator('button[data-tip="Record voiceover"]').click();
    await page.locator('.studio').waitFor();
    await page.waitForFunction(() => document.querySelector('.meter .db')?.textContent !== '−∞ dB', null, { timeout: 15000, polling: 100 });
    step('mic check');
    await page.locator('.insp-section header', { hasText: 'Recording options' }).click();
    await page.locator('button', { hasText: 'Check microphone' }).click();
    await page.locator('.checks').waitFor({ timeout: 10000 });
    const checks = await page.locator('.checks').innerText(); console.log('  ' + checks.replace(/\n/g, ' | '));
    step('record 3 s over the video (countdown off)');
    await page.evaluate(async () => { const s = window.__fc.state; await s.savePrefs({ recording: { playVideo: true, countdown: false, preroll: 0, trimSilence: false, monitor: false } }); s.player.current.seek(1); });
    await page.keyboard.press('r');
    await page.locator('.rec-btn.stop').waitFor(); const recT0 = Date.now();
    await page.waitForTimeout(1500); await page.keyboard.press('m');
    await page.waitForTimeout(1600);
    const recT1 = Date.now(); await page.keyboard.press('r');
    await page.waitForFunction(() => window.__fc.state.project.value.clips.some(c => c.name === 'Voiceover'), null, { timeout: 20000, polling: 100 });
    const rec = await page.evaluate(() => { const s = window.__fc.state; const c = s.project.value.clips.find(c => c.name === 'Voiceover'); const a = s.media.value.get(c.mediaId); return { c, a }; });
    console.log(`  take: start ${rec.c.start.toFixed(3)}s, duration ${rec.c.duration.toFixed(2)}s, markers ${rec.c.markers.length}, ${JSON.stringify(rec.a.recording)}`);
    const wavPath = await page.evaluate(id => window.__fc.api('/api/media').then(l => { const a = l.find(a => a.id === id); return a.folder + '/' + a.fileName; }), rec.a.id);
    const pr = JSON.parse((await run(ffprobe, ['-v', 'quiet', '-show_streams', '-of', 'json', wavPath])).out).streams[0];
    console.log(`  file: ${pr.codec_name} ${pr.sample_rate} Hz ${pr.channels} ch ${pr.bits_per_sample} bit`);
    assert.equal(pr.codec_name, 'pcm_s24le'); assert.equal(+pr.bits_per_sample, 24);
    assert.ok(Math.abs(rec.c.duration - (recT1 - recT0) / 1000) < 0.4, `take length ${rec.c.duration} vs ${(recT1 - recT0) / 1000}`);
    assert.ok(Math.abs(rec.c.start - 1) < 0.25, 'take placed at the playhead (latency-compensated)');
    assert.equal(rec.c.markers.length, 1, 'mistake marker saved');
    const { out: vol } = await run(ffmpeg, ['-hide_banner', '-i', wavPath, '-af', 'volumedetect', '-f', 'null', '-']).catch(e => ({ out: e.message }));
    step('retake keeps both takes');
    await page.keyboard.press('Shift+R'); await page.locator('.rec-btn.stop').waitFor(); await page.waitForTimeout(2000); await page.keyboard.press('r');
    await page.waitForFunction(() => window.__fc.state.project.value.clips.find(c => c.name === 'Voiceover')?.takes?.length === 2, null, { timeout: 20000, polling: 100 });
    assert.equal(await page.evaluate(() => window.__fc.state.project.value.clips.filter(c => c.name === 'Voiceover').length), 1, 'retake replaces in place, no clutter');
    step('clean voice + compare');
    await page.locator('.rec-secondary button', { hasText: 'Clean voice' }).click();
    const prof = await page.evaluate(() => window.__fc.state.project.value.clips.find(c => c.name === 'Voiceover').audioFx.profile); assert.equal(prof, 'clean');
    step('auto balance + ducking');
    await page.locator('button', { hasText: 'Auto balance levels' }).click();
    await page.waitForFunction(() => window.__fc.state.history.value.past.some(h => h.label === 'Auto balance'), null, { timeout: 60000, polling: 100 });
    await page.locator('.check-row', { hasText: 'Lower music while speaking' }).locator('.switch').click();
    await page.waitForFunction(() => window.__fc.state.project.value.clips.some(c => c.duckKeys?.length), null, { timeout: 30000, polling: 100 });
    const mix = await page.evaluate(() => window.__fc.state.project.value.clips.filter(c => c.kind === 'audio').map(c => ({ name: c.name, vol: c.volume, duck: c.duckKeys?.length || 0 })));
    console.log('  mix: ' + JSON.stringify(mix));
    assert.ok(mix.find(m => m.name !== 'Voiceover').duck > 0, 'music gets ducking keys');
    await page.screenshot({ path: path.join(shots, '11-studio.png') });
    if (await page.locator('.script').count() === 0) await page.locator('.rec-secondary button', { hasText: 'Script' }).click();
    await page.locator('.script-edit').fill(['Welcome to FrameCut.', 'This is the second line of the script.', 'And a third.'].join('\n'));
    await page.locator('.script-head button', { hasText: 'Read' }).click();
    await page.screenshot({ path: path.join(shots, '12-script.png') });
    step('waveform editor: silence a range');
    await page.evaluate(() => { const s = window.__fc.state; s.selection.value = [s.project.value.clips.find(c => c.name === 'Voiceover').id]; });
    const box = await page.locator('.we-canvas').boundingBox();
    await page.mouse.move(box.x + box.width * 0.3, box.y + box.height / 2); await page.mouse.down(); await page.mouse.move(box.x + box.width * 0.5, box.y + box.height / 2, { steps: 5 }); await page.mouse.up();
    await page.locator('.we-bar button[data-tip="Silence selection"]').click();
    const keys = await page.evaluate(() => window.__fc.state.project.value.clips.find(c => c.name === 'Voiceover').volumeKeys); assert.ok(keys?.some(k => k.v === 0), 'silenced range has zero-gain keys');
    await page.keyboard.press('Control+z');
    assert.ok(!(await page.evaluate(() => window.__fc.state.project.value.clips.find(c => c.name === 'Voiceover').volumeKeys?.some(k => k.v === 0))), 'undo restores');
    step('export and inspect the mix');
    await page.locator('button[data-tip="Close studio"]').click();
    const out = path.join(temp, 'mix.wav');
    const settings = { format: 'wav', resolution: 720, fps: 30, output: out };
    const res = await page.evaluate(async st => { const { state, api } = window.__fc; await state.saveNow(); const { job } = await api('/api/export', { project: state.project.value, rasters: {}, settings: st }); for (;;) { const j = await api('/api/jobs/' + job); if (j.status === 'done') return j.result; if (j.status === 'failed') throw Error(j.error); await new Promise(r => setTimeout(r, 300)); } }, settings);
    const { err } = await run(ffmpeg, ['-hide_banner', '-i', out, '-af', 'astats=metadata=0', '-f', 'null', '-']);
    const peak = +(/Peak level dB: (-?[\d.inf]+)/.exec(err.split('Overall')[1] || '')?.[1] ?? 0);
    console.log(`  export: ${res.duration.toFixed(2)} s, overall peak ${peak} dBFS`);
    assert.ok(peak <= -0.9, 'mix peaks stay under the -1 dB ceiling');
    step('reopen keeps takes, profile, ducking');
    await page.locator('button[data-tip="Back to projects"]').click(); await page.locator('.project-card').first().click(); await page.locator('.editor').waitFor();
    const after = await page.evaluate(() => { const c = window.__fc.state.project.value.clips.find(c => c.name === 'Voiceover'); return { takes: c.takes.length, profile: c.audioFx.profile, duck: window.__fc.state.project.value.settings.ducking?.on }; });
    assert.deepEqual(after, { takes: 2, profile: 'clean', duck: true });
    console.log('ERRORS', JSON.stringify(errors));
    assert.deepEqual(errors.filter(e => !/Autofill|DevTools|Security/.test(e)), []);
    console.log('PASS: studio');
  } catch (e) { console.error('FAIL', e.message); await page?.screenshot({ path: path.join(shots, 'fail-studio.png') }).catch(() => {}); console.log('ERRORS', JSON.stringify(errors)); process.exitCode = 1; }
  finally { await app?.close(); await fs.rm(temp, { recursive: true, force: true }).catch(() => {}); }
})();
